-- ---------------------------------------------------------------------
-- 1. Tabelas base (sem dependencias)
-- ---------------------------------------------------------------------

CREATE TABLE T_ECMV_ROLE (
                             ID_ROLE  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                             NM_ROLE  VARCHAR2(50) NOT NULL,
                             CONSTRAINT PK_ECMV_ROLE PRIMARY KEY (ID_ROLE)
);

CREATE TABLE T_ECMV_COMUNIDADE (
                                   ID_COMUNIDADE  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                   NM_COMUNIDADE  VARCHAR2(150) NOT NULL,
                                   CONSTRAINT PK_ECMV_COMUNIDADE PRIMARY KEY (ID_COMUNIDADE)
);

CREATE TABLE T_ECMV_MISSAO (
                               ID_MISSAO           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                               NM_MISSAO           VARCHAR2(150) NOT NULL,
                               CATEGORIA_MISSAO    VARCHAR2(50) NOT NULL,
                               DESCRICAO_MISSAO    VARCHAR2(500),
                               DIFICULDADE_MISSAO  VARCHAR2(30) NOT NULL,
                               ATIVA_MISSAO        CHAR(1) DEFAULT 'S' NOT NULL,
                               CONSTRAINT PK_ECMV_MISSAO PRIMARY KEY (ID_MISSAO),
                               CONSTRAINT CK_ECMV_MISSAO_ACT CHECK (ATIVA_MISSAO IN ('S','N'))
);

CREATE TABLE T_ECMV_CAMADA_VERIFICACAO (
                                           ID_CAMADA_VERIFICACAO  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                           NM_CAMADA_VERIFICACAO  VARCHAR2(50) NOT NULL,
                                           CONSTRAINT PK_ECMV_CAMADA_VERIF PRIMARY KEY (ID_CAMADA_VERIFICACAO)
);

CREATE TABLE T_ECMV_FORMULA_ECOSCORE (
                                         ID_FORMULA_ECOSCORE                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                         VERSAO_FORMULA_ECOSCORE             NUMBER(5) NOT NULL,
                                         PESO_IMPACTO_FORMULA_ECOSCORE       NUMBER(5,2) NOT NULL,
                                         PESO_INTENSIDADE_FORMULA_ECOSCORE   NUMBER(5,2) NOT NULL,
                                         PESO_EVIDENCIA_FORMULA_ECOSCORE     NUMBER(5,2) NOT NULL,
                                         PESO_DIFICULDADE_FORMULA_ECOSCORE   NUMBER(5,2) NOT NULL,
                                         PESO_CONSISTENCIA_FORMULA_ECOSCORE  NUMBER(5,2) NOT NULL,
                                         CONSTRAINT PK_ECMV_FORMULA_SCORE PRIMARY KEY (ID_FORMULA_ECOSCORE)
);

CREATE TABLE T_ECMV_BADGE (
                              ID_BADGE         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                              NM_BADGE         VARCHAR2(100) NOT NULL,
                              DESCRICAO_BADGE  VARCHAR2(300),
                              CONSTRAINT PK_ECMV_BADGE PRIMARY KEY (ID_BADGE)
);

-- ---------------------------------------------------------------------
-- 2. Tabelas intermediarias e dependentes
-- ---------------------------------------------------------------------

CREATE TABLE T_ECMV_USUARIO (
                                ID_USUARIO           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                NM_USUARIO           VARCHAR2(150) NOT NULL,
                                EMAIL_USUARIO        VARCHAR2(150) NOT NULL,
                                SENHA_HASH_USUARIO   VARCHAR2(255) NOT NULL,
                                DT_CADASTRO_USUARIO  DATE DEFAULT SYSDATE NOT NULL,
                                ID_ROLE              NUMBER(10) NOT NULL,
                                CONSTRAINT PK_ECMV_USUARIO PRIMARY KEY (ID_USUARIO),
                                CONSTRAINT UK_ECMV_USER_EMAIL UNIQUE (EMAIL_USUARIO),
                                CONSTRAINT FK_ECMV_USER_ROLE FOREIGN KEY (ID_ROLE)
                                    REFERENCES T_ECMV_ROLE (ID_ROLE)
);

CREATE TABLE T_ECMV_FLORESTA_DIGITAL (
                                         ID_FLORESTA_DIGITAL             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                         NIVEL_ATUAL_FLORESTA_DIGITAL    NUMBER(5) DEFAULT 1 NOT NULL,
                                         ESTADO_VISUAL_FLORESTA_DIGITAL  VARCHAR2(100),
                                         ID_COMUNIDADE                   NUMBER(10) NOT NULL,
                                         CONSTRAINT PK_ECMV_FLORESTA PRIMARY KEY (ID_FLORESTA_DIGITAL),
                                         CONSTRAINT FK_ECMV_FLORESTA_COM FOREIGN KEY (ID_COMUNIDADE)
                                             REFERENCES T_ECMV_COMUNIDADE (ID_COMUNIDADE)
);

CREATE TABLE T_ECMV_ARVORE_DIGITAL (
                                       ID_ARVORE_DIGITAL             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                       NIVEL_ATUAL_ARVORE_DIGITAL    NUMBER(5) DEFAULT 1 NOT NULL,
                                       ESTADO_VISUAL_ARVORE_DIGITAL  VARCHAR2(100),
                                       ID_USUARIO                    NUMBER(10) NOT NULL,
                                       ID_FLORESTA_DIGITAL           NUMBER(10),
                                       CONSTRAINT PK_ECMV_ARVORE PRIMARY KEY (ID_ARVORE_DIGITAL),
                                       CONSTRAINT FK_ECMV_ARVORE_USER FOREIGN KEY (ID_USUARIO)
                                           REFERENCES T_ECMV_USUARIO (ID_USUARIO),
                                       CONSTRAINT FK_ECMV_ARVORE_FOREST FOREIGN KEY (ID_FLORESTA_DIGITAL)
                                           REFERENCES T_ECMV_FLORESTA_DIGITAL (ID_FLORESTA_DIGITAL)
);

CREATE TABLE T_ECMV_QRCODE (
                               ID_QRCODE           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                               CODIGO_QRCODE       VARCHAR2(100) NOT NULL,
                               DT_VALIDADE_QRCODE  DATE NOT NULL,
                               ID_MISSAO           NUMBER(10) NOT NULL,
                               CONSTRAINT PK_ECMV_QRCODE PRIMARY KEY (ID_QRCODE),
                               CONSTRAINT UK_ECMV_QR_CODE UNIQUE (CODIGO_QRCODE),
                               CONSTRAINT FK_ECMV_QR_MISSION FOREIGN KEY (ID_MISSAO)
                                   REFERENCES T_ECMV_MISSAO (ID_MISSAO)
);

CREATE TABLE T_ECMV_SUBMISSAO (
                                  ID_SUBMISSAO        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                  STATUS_SUBMISSAO    VARCHAR2(30) NOT NULL,
                                  DT_ENVIO_SUBMISSAO  DATE DEFAULT SYSDATE NOT NULL,
                                  ID_USUARIO          NUMBER(10) NOT NULL,
                                  ID_MISSAO           NUMBER(10) NOT NULL,
                                  CONSTRAINT PK_ECMV_SUBMISSAO PRIMARY KEY (ID_SUBMISSAO),
                                  CONSTRAINT FK_ECMV_SUB_USER FOREIGN KEY (ID_USUARIO)
                                      REFERENCES T_ECMV_USUARIO (ID_USUARIO),
                                  CONSTRAINT FK_ECMV_SUB_MISSION FOREIGN KEY (ID_MISSAO)
                                      REFERENCES T_ECMV_MISSAO (ID_MISSAO)
);

CREATE TABLE T_ECMV_RANKING_AGREGADO (
                                         ID_RANKING_AGREGADO               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                         ECOPOINTS_TOTAL_RANKING_AGREGADO  NUMBER(12) DEFAULT 0 NOT NULL,
                                         POSICAO_RANKING_AGREGADO          NUMBER(10) NOT NULL,
                                         ID_USUARIO                        NUMBER(10) NOT NULL,
                                         CONSTRAINT PK_ECMV_RANKING PRIMARY KEY (ID_RANKING_AGREGADO),
                                         CONSTRAINT FK_ECMV_RANK_USER FOREIGN KEY (ID_USUARIO)
                                             REFERENCES T_ECMV_USUARIO (ID_USUARIO)
);

CREATE TABLE T_ECMV_PREMIACAO (
                                  ID_PREMIACAO                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                  VALOR_CONTA_ENERGIA_PREMIACAO  NUMBER(10,2) NOT NULL,
                                  DT_PROCESSAMENTO_PREMIACAO     DATE,
                                  ID_USUARIO                     NUMBER(10) NOT NULL,
                                  CONSTRAINT PK_ECMV_PREMIACAO PRIMARY KEY (ID_PREMIACAO),
                                  CONSTRAINT FK_ECMV_PREM_USER FOREIGN KEY (ID_USUARIO)
                                      REFERENCES T_ECMV_USUARIO (ID_USUARIO)
);

CREATE TABLE T_ECMV_AUDITORIA (
                                  ID_AUDITORIA         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                  ENTIDADE_AUDITORIA   VARCHAR2(100) NOT NULL,
                                  ACAO_AUDITORIA       VARCHAR2(200) NOT NULL,
                                  DT_EVENTO_AUDITORIA  DATE DEFAULT SYSDATE NOT NULL,
                                  ID_USUARIO           NUMBER(10) NOT NULL,
                                  CONSTRAINT PK_ECMV_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
                                  CONSTRAINT FK_ECMV_AUD_USER FOREIGN KEY (ID_USUARIO)
                                      REFERENCES T_ECMV_USUARIO (ID_USUARIO)
);

CREATE TABLE T_ECMV_USUARIO_BADGE (
                                      ID_USUARIO                    NUMBER(10) NOT NULL,
                                      ID_BADGE                      NUMBER(10) NOT NULL,
                                      DT_DESBLOQUEIO_USUARIO_BADGE  DATE DEFAULT SYSDATE NOT NULL,
                                      CONSTRAINT PK_ECMV_USER_BADGE PRIMARY KEY (ID_USUARIO, ID_BADGE),
                                      CONSTRAINT FK_ECMV_UB_USER FOREIGN KEY (ID_USUARIO)
                                          REFERENCES T_ECMV_USUARIO (ID_USUARIO),
                                      CONSTRAINT FK_ECMV_UB_BADGE FOREIGN KEY (ID_BADGE)
                                          REFERENCES T_ECMV_BADGE (ID_BADGE)
);

-- ---------------------------------------------------------------------
-- 3. Tabelas de validacao, evidencias e movimentacoes
-- ---------------------------------------------------------------------

CREATE TABLE T_ECMV_EVIDENCIA (
                                  ID_EVIDENCIA                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                  TP_EVIDENCIA                  VARCHAR2(30) NOT NULL,
                                  REFERENCIA_ARQUIVO_EVIDENCIA  VARCHAR2(500) NOT NULL,
                                  DT_CAPTURA_EVIDENCIA          DATE DEFAULT SYSDATE NOT NULL,
                                  ID_SUBMISSAO                  NUMBER(10) NOT NULL,
                                  CONSTRAINT PK_ECMV_EVIDENCIA PRIMARY KEY (ID_EVIDENCIA),
                                  CONSTRAINT FK_ECMV_EVID_SUB FOREIGN KEY (ID_SUBMISSAO)
                                      REFERENCES T_ECMV_SUBMISSAO (ID_SUBMISSAO)
);

CREATE TABLE T_ECMV_ANALISE_IA (
                                   ID_ANALISE_IA                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                   OBJETO_IDENTIFICADO_ANALISE_IA  VARCHAR2(150),
                                   CONFIANCA_ANALISE_IA            NUMBER(5,2) NOT NULL,
                                   DUPLICIDADE_ANALISE_IA          CHAR(1) DEFAULT 'N' NOT NULL,
                                   ID_EVIDENCIA                    NUMBER(10) NOT NULL,
                                   CONSTRAINT PK_ECMV_ANALISE_IA PRIMARY KEY (ID_ANALISE_IA),
                                   CONSTRAINT CK_ECMV_AI_DUP CHECK (DUPLICIDADE_ANALISE_IA IN ('S','N')),
                                   CONSTRAINT FK_ECMV_AI_EVID FOREIGN KEY (ID_EVIDENCIA)
                                       REFERENCES T_ECMV_EVIDENCIA (ID_EVIDENCIA)
);

CREATE TABLE T_ECMV_VALIDACAO_ECOGUARD (
                                           ID_VALIDACAO_ECOGUARD          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                           RESULTADO_VALIDACAO_ECOGUARD   VARCHAR2(200) NOT NULL,
                                           SCORE_RISCO_VALIDACAO_ECOGUARD NUMBER(5,2) NOT NULL,
                                           ID_SUBMISSAO                   NUMBER(10) NOT NULL,
                                           CONSTRAINT PK_ECMV_VAL_ECOGUARD PRIMARY KEY (ID_VALIDACAO_ECOGUARD),
                                           CONSTRAINT FK_ECMV_VAL_SUB FOREIGN KEY (ID_SUBMISSAO)
                                               REFERENCES T_ECMV_SUBMISSAO (ID_SUBMISSAO)
);

CREATE TABLE T_ECMV_VERIFICACAO_SUBMISSAO (
                                              ID_VALIDACAO_ECOGUARD     NUMBER(10) NOT NULL,
                                              ID_CAMADA_VERIFICACAO     NUMBER(10) NOT NULL,
                                              DT_VERIFICACAO_SUBMISSAO  DATE DEFAULT SYSDATE NOT NULL,
                                              CONSTRAINT PK_ECMV_VERIF_SUB
                                                  PRIMARY KEY (ID_VALIDACAO_ECOGUARD, ID_CAMADA_VERIFICACAO),
                                              CONSTRAINT FK_ECMV_VS_VAL FOREIGN KEY (ID_VALIDACAO_ECOGUARD)
                                                  REFERENCES T_ECMV_VALIDACAO_ECOGUARD (ID_VALIDACAO_ECOGUARD),
                                              CONSTRAINT FK_ECMV_VS_CAM FOREIGN KEY (ID_CAMADA_VERIFICACAO)
                                                  REFERENCES T_ECMV_CAMADA_VERIFICACAO (ID_CAMADA_VERIFICACAO)
);

CREATE TABLE T_ECMV_ECOSCORE (
                                 ID_ECOSCORE              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                 ECOSCORE_FINAL_ECOSCORE  NUMBER(5,2) NOT NULL,
                                 ID_FORMULA_ECOSCORE      NUMBER(10) NOT NULL,
                                 ID_SUBMISSAO             NUMBER(10) NOT NULL,
                                 CONSTRAINT PK_ECMV_ECOSCORE PRIMARY KEY (ID_ECOSCORE),
                                 CONSTRAINT FK_ECMV_SCORE_FORM FOREIGN KEY (ID_FORMULA_ECOSCORE)
                                     REFERENCES T_ECMV_FORMULA_ECOSCORE (ID_FORMULA_ECOSCORE),
                                 CONSTRAINT FK_ECMV_SCORE_SUB FOREIGN KEY (ID_SUBMISSAO)
                                     REFERENCES T_ECMV_SUBMISSAO (ID_SUBMISSAO)
);

CREATE TABLE T_ECMV_MOVIMENTO_ECOPOINTS (
                                            ID_MOVIMENTO_ECOPOINTS          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                            ID_SUBMISSAO                    NUMBER(10) NOT NULL,
                                            TP_MOVIMENTO_ECOPOINTS          VARCHAR2(30) NOT NULL,
                                            QUANTIDADE_MOVIMENTO_ECOPOINTS  NUMBER(10) NOT NULL,
                                            CONSTRAINT PK_ECMV_MOV_ECOPOINTS PRIMARY KEY (ID_MOVIMENTO_ECOPOINTS),
                                            CONSTRAINT FK_ECMV_MOV_SUB FOREIGN KEY (ID_SUBMISSAO)
                                                REFERENCES T_ECMV_SUBMISSAO (ID_SUBMISSAO)
);

CREATE TABLE T_ECMV_MOVIMENTO_FRUTO (
                                        ID_MOVIMENTO_FRUTO          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
                                        ID_USUARIO_ORIGEM           NUMBER(10) NOT NULL,
                                        ID_USUARIO_DESTINO          NUMBER(10) NOT NULL,
                                        QUANTIDADE_MOVIMENTO_FRUTO  NUMBER(10) NOT NULL,
                                        ID_ARVORE_DIGITAL           NUMBER(10) NOT NULL,
                                        DT_MOVIMENTO_FRUTO          DATE DEFAULT SYSDATE NOT NULL,
                                        CONSTRAINT PK_ECMV_MOV_FRUTO PRIMARY KEY (ID_MOVIMENTO_FRUTO),
                                        CONSTRAINT FK_ECMV_FRUTO_ORIG FOREIGN KEY (ID_USUARIO_ORIGEM)
                                            REFERENCES T_ECMV_USUARIO (ID_USUARIO),
                                        CONSTRAINT FK_ECMV_FRUTO_DEST FOREIGN KEY (ID_USUARIO_DESTINO)
                                            REFERENCES T_ECMV_USUARIO (ID_USUARIO),
                                        CONSTRAINT FK_ECMV_FRUTO_TREE FOREIGN KEY (ID_ARVORE_DIGITAL)
                                            REFERENCES T_ECMV_ARVORE_DIGITAL (ID_ARVORE_DIGITAL)
);

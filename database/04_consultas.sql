SELECT u.NM_USUARIO,
       SUM(m.QUANTIDADE_MOVIMENTO_ECOPOINTS) AS ECOPOINTS
FROM T_ECMV_USUARIO u
         JOIN T_ECMV_SUBMISSAO s
              ON s.ID_USUARIO = u.ID_USUARIO
         JOIN T_ECMV_MOVIMENTO_ECOPOINTS m
              ON m.ID_SUBMISSAO = s.ID_SUBMISSAO
WHERE m.TP_MOVIMENTO_ECOPOINTS = 'CREDITO'
GROUP BY u.NM_USUARIO
ORDER BY ECOPOINTS DESC;

SELECT s.ID_SUBMISSAO,
       mi.NM_MISSAO,
       s.STATUS_SUBMISSAO,
       TO_CHAR(s.DT_ENVIO_SUBMISSAO, 'DD/MM/YYYY HH24:MI')
           AS ENVIADA_EM
FROM T_ECMV_SUBMISSAO s
         JOIN T_ECMV_MISSAO mi
              ON mi.ID_MISSAO = s.ID_MISSAO
WHERE s.ID_USUARIO = 1
ORDER BY s.DT_ENVIO_SUBMISSAO DESC;

SELECT STATUS_SUBMISSAO,
       COUNT(*) AS QUANTIDADE
FROM T_ECMV_SUBMISSAO
GROUP BY STATUS_SUBMISSAO
ORDER BY QUANTIDADE DESC;

SELECT mi.NM_MISSAO,
       mi.CATEGORIA_MISSAO,
       COUNT(s.ID_SUBMISSAO) AS VEZES_CONCLUIDA,
       NVL(SUM(mi.PONTOS_MISSAO), 0) AS PONTOS_DISTRIBUIDOS
FROM T_ECMV_MISSAO mi
         LEFT JOIN T_ECMV_SUBMISSAO s
                   ON s.ID_MISSAO = mi.ID_MISSAO
                       AND s.STATUS_SUBMISSAO = 'APROVADA'
GROUP BY mi.NM_MISSAO, mi.CATEGORIA_MISSAO
ORDER BY VEZES_CONCLUIDA DESC;

SELECT RESULTADO_VALIDACAO_ECOGUARD,
       COUNT(*) AS AVALIACOES,
       ROUND(AVG(SCORE_RISCO_VALIDACAO_ECOGUARD), 1) AS MEDIA_RISCO,
       MIN(SCORE_RISCO_VALIDACAO_ECOGUARD) AS MENOR_RISCO,
       MAX(SCORE_RISCO_VALIDACAO_ECOGUARD) AS MAIOR_RISCO
FROM T_ECMV_VALIDACAO_ECOGUARD
GROUP BY RESULTADO_VALIDACAO_ECOGUARD;

SELECT e.ID_EVIDENCIA,
       u.NM_USUARIO,
       mi.NM_MISSAO,
       e.TP_EVIDENCIA,
       e.TP_ARQUIVO_EVIDENCIA,
       DBMS_LOB.GETLENGTH(e.ARQUIVO_EVIDENCIA) AS TAMANHO_BYTES,
       s.STATUS_SUBMISSAO
FROM T_ECMV_EVIDENCIA e
         JOIN T_ECMV_SUBMISSAO s
              ON s.ID_SUBMISSAO = e.ID_SUBMISSAO
         JOIN T_ECMV_USUARIO u
              ON u.ID_USUARIO = s.ID_USUARIO
         JOIN T_ECMV_MISSAO mi
              ON mi.ID_MISSAO = s.ID_MISSAO
WHERE e.TP_EVIDENCIA IN ('FOTO', 'VIDEO')
ORDER BY e.DT_CAPTURA_EVIDENCIA DESC;

SELECT u.NM_USUARIO,
       mi.NM_MISSAO,
       p.QT_PROGRESSO_MISSAO || '/' || mi.META_MISSAO AS PROGRESSO,
       ROUND(p.QT_PROGRESSO_MISSAO * 100 / mi.META_MISSAO)
                                                      AS PERCENTUAL
FROM T_ECMV_PROGRESSO_MISSAO p
         JOIN T_ECMV_USUARIO u
              ON u.ID_USUARIO = p.ID_USUARIO
         JOIN T_ECMV_MISSAO mi
              ON mi.ID_MISSAO = p.ID_MISSAO
ORDER BY PERCENTUAL DESC;

SELECT CATEGORIA_MISSAO,
       DIFICULDADE_MISSAO,
       COUNT(*) AS QTD_MISSOES,
       ROUND(AVG(PONTOS_MISSAO)) AS MEDIA_PONTOS
FROM T_ECMV_MISSAO
WHERE ATIVA_MISSAO = 'S'
GROUP BY CATEGORIA_MISSAO, DIFICULDADE_MISSAO
ORDER BY CATEGORIA_MISSAO;

SELECT ID_EVIDENCIA, TP_ARQUIVO_EVIDENCIA, ARQUIVO_EVIDENCIA
FROM T_ECMV_EVIDENCIA
